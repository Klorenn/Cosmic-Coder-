/**
 * XP gems dropped on the floor (systems/xpGems.js): blue 1-9 XP 8x8, green 10-49 10x10, red 50+ 12x12.
 * 2-frame shine loop. Generated by scripts/assets/gen-sprites.mjs (--only=xp-gem-blue,...).
 */
const GEM = (tier, size) => ({
  id: `xp-gem-${tier}`,
  tier,
  key: `xp-gem-${tier}`,
  anim: `xp-gem-${tier}-anim`,
  file: `items/xp-gem-${tier}.png`,
  frameWidth: size,
  frameHeight: size,
  frames: 2,
  frameRate: 3
});
export const XP_GEM_SPRITES = [GEM('blue', 8), GEM('green', 10), GEM('red', 12)];

/** Lookup helper: v2 sprite entry by enemy / mini-boss / boss id. */
export function getEnemySprite(id) {
  return ENEMY_SPRITES.find((s) => s.id === id) || null;
}

/** Queue every v2 enemy spritesheet. Call from BootScene.preload(). */
export function preloadEnemyAssets(scene) {
  for (const s of [...ENEMY_SPRITES, ...XP_GEM_SPRITES]) {
    if (scene.textures.exists(s.key)) continue;
    scene.load.spritesheet(s.key, getAssetPath(`${SPRITE_DIR}/${s.file}`), {
      frameWidth: s.frameWidth,
      frameHeight: s.frameHeight
    });
  }
}

/** Register looping idle/walk anims for every loaded v2 sheet. Call from BootScene.create(). */
export function createEnemyAnims(scene) {
  for (const s of [...ENEMY_SPRITES, ...XP_GEM_SPRITES]) {
    if (!scene.textures.exists(s.key) || scene.anims.exists(s.anim)) continue;
    scene.anims.create({
      key: s.anim,
      frames: scene.anims.generateFrameNumbers(s.key, { start: 0, end: s.frames - 1 }),
      frameRate: s.frameRate,
      repeat: -1
    });
  }
}

/** Extra art generated with the item icons: glow sprite (tinted at runtime) and shrine pieces. */
export const ITEM_FX_IMAGES = [
  { key: 'fx-glow', file: 'items/fx-glow.png' },
  { key: 'shrine-pedestal', file: 'items/shrine-pedestal.png' },
  ...['power', 'gamble', 'xp', 'shield', 'chaos'].map((id) => ({ key: `shrine-${id}`, file: `items/shrine-${id}.png` }))
];

/**
 * Queue item icons under `item-<id>` (+ glow/shrine art). Must run in preload(): BootScene's
 * generateItemTextures() skips keys that already exist, so the PNG wins over the procedural one.
 */
export function preloadItemIcons(scene) {
  for (const it of [...ITEM_ICONS, ...ITEM_FX_IMAGES]) {
    if (scene.textures.exists(it.key)) continue;
    scene.load.image(it.key, getAssetPath(`${SPRITE_DIR}/${it.file}`));
  }
}
