const reducedMotion = () => {
  try { return !!window.matchMedia?.('(prefers-reduced-motion: reduce)')?.matches; } catch (_) { return false; }
};
export const isTouch = () => {
  try { return !!window.matchMedia?.('(pointer: coarse)')?.matches; } catch (_) { return false; }
};
export const colorInt = (c) => colorToInt(c);

/** Logical canvas units per CSS px. */
export function overlayUnit(scene) {
  const k = cssPerUnit(scene.scale?.displaySize?.width, scene.scale?.width, scene.cameras?.main?.zoom);
  return Phaser.Math.Clamp(1 / k, 0.6, 3.2);
}

/** Logical units per art pixel (2 css px). */
export const artPx = (u) => PX_CSS_PER_ART * u;

/**
 * Pre-layout numbers so a caller can size the panel to its content before createOverlay():
 * { u, bodyW, bodyH } in logical units for a panel of max width/height (css) with footerH (css).
 */
export function overlayMetrics(scene, { width = 880, height = 600, footerH = 0 } = {}) {
  const u = overlayUnit(scene);
  const view = visibleRect(scene.scale.width, scene.scale.height, scene.cameras.main.zoom);
  const frame = overlayFrame(view, u, { maxW: width, maxH: height, margin: 12 });
  return { u, bodyW: frame.w - 40 * u, bodyH: frame.h - overlayChromeH(footerH) * u };
}

/** Panel height (css) that fits `contentLogical` units of body content, capped at maxCss. */
export function fitPanelHeight(u, contentLogical, footerH, maxCss = 600) {
  return Math.min(maxCss, overlayChromeH(footerH) + contentLogical / u + 8);
}

/** css size -> integer art scale for the pixel font (cap height = 7 * scale css px). */
export function fontArtScale(size) {
  if (size >= 19) return 3;
  if (size >= 10) return 2;
  return 1;
}

/**
 * UI text sized in CSS px. Bitmap pixel font (integer art scale, hard ink drop shadow) for everything,
 * except multi-line descriptions capped with maxLines, which keep the system sans (high resolution).
 */
export function ovText(scene, x, y, str, { u = 1, size = 14, color = OV.text, bold = false, align = 'left', wrap = 0, maxLines = 0, alpha = 1 } = {}) {
  if ((wrap > 0 && maxLines > 0) || !hasUiFont(scene)) {
    const style = { fontFamily: OV.font, fontSize: `${Math.round(size * u)}px`, color: typeof color === 'number' ? `#${color.toString(16).padStart(6, '0')}` : color, fontStyle: bold ? 'bold' : 'normal', align, resolution: 2 };
    if (wrap > 0) style.wordWrap = { width: wrap, useAdvancedWrap: true };
    if (maxLines > 0) style.maxLines = maxLines;
    const tx = scene.add.text(x, y, str ?? '', style).setAlpha(alpha);
    try { tx.texture.setFilter(Phaser.Textures.FilterMode.LINEAR); } catch (_) { /* canvas renderer */ }
    return tx;
  }
  const fontSize = FONT_META.size * fontArtScale(size) * u;
  return pixelText(scene, x, y, str ?? '', { size: fontSize, color, align, maxWidth: wrap > 0 ? wrap : 0, lineSpacing: wrap > 0 ? 2 * u : 0 }).setAlpha(alpha);
}

/** Trim a single-line text to maxW with an ellipsis. */
export function fitText(tx, maxW) {
  const full = tx.text;
  if (tx.width <= maxW || !full) return tx;
  let lo = 0; let hi = full.length;
  while (lo < hi) {
    const mid = Math.ceil((lo + hi) / 2);
    tx.setText(`${full.slice(0, mid).trimEnd()}…`);
    if (tx.width <= maxW) lo = mid; else hi = mid - 1;
  }
  tx.setText(`${full.slice(0, lo).trimEnd()}…`);
  return tx;
}

/** Greyish colours (locked / disabled states) tint the greyscale icon; everything else keeps its own palette. */
const isDimColor = (c) => c != null && familyOf(c) === 'neutral' && ((colorToInt(c) >> 8) & 255) < 0xc0;

/**
 * Pixel icon centred on (0,0); size in logical units (the art snaps to 16 or 24 px at 1-3 css px per
 * art pixel, whichever is closest). color: full-colour art unless the colour is a dim grey (locked).
 * opts.tint: force the greyscale variant tinted with `color`.
 */
export function pixelIcon(scene, name, size, color = undefined, { tint = false } = {}) {
  const u = overlayUnit(scene);
  const css = size / u;
  const opts = [[16, 1], [24, 1], [16, 2], [24, 2], [16, 3]];
  let best = opts[0];
  opts.forEach((o) => { if (Math.abs(o[0] * o[1] - css) < Math.abs(best[0] * best[1] - css)) best = o; });
  const tintC = tint || isDimColor(color) ? color : null;
  const name2 = UI_ICON_NAMES.includes(name) ? name : 'star';
  return uiIcon(scene, 0, 0, name2, { px: best[1] * u, big: best[0] === 24, tint: tintC });
}

/** Gem (same art as the BITS counter on the title corners); amber colours use the amber gem. */
export function gemIcon(scene, size, color = OV.amber) {
  return pixelIcon(scene, familyOf(color) === 'amber' ? 'gem-amber' : 'gem', size);
}

/** Bevelled icon tile (x, y top-left, size logical) in the colour's family, for upgrade / settings rows. */
export function iconTile(scene, x, y, size, color, { u = 1 } = {}) {
  return pixelPanel(scene, x, y, size, size, tileSkin(familyOf(color)), { px: artPx(u) });
}

/** Pixel card: container at (x,y) top-left, w x h. setSelected(sel, dim) swaps the skin. */
export function glassCard(scene, x, y, w, h, { u = 1, selected = false, accent = OV.violet } = {}) {
  const c = scene.add.container(x, y);
  const fam = familyOf(accent);
  const panel = pixelPanel(scene, 0, 0, w, h, 'card', { px: artPx(u) });
  c.add(panel);
  const draw = (sel, dim = false) => panel.setSkin(sel ? selectedCardSkin(fam) : (dim ? 'card-dim' : 'card'));
  draw(selected);
  return { container: c, g: panel, w, h, setSelected: (s, dim) => draw(s, dim) };
}

/**
 * Pixel button (raised bevel; hover brightens, press sinks 1 art px). label: string, or { icon } / { icon, text } / { gem }.
 * Visual height 40 css (44 on touch), hit area >= 48 css. Returns { container, setLabel, setEnabled, setPrimary, w, h }.
 */
export function pillButton(scene, label, onClick, { u = 1, primary = false, minW = 0, h: hCss = 0, accent = OV.violet, round = false } = {}) {
  const c = scene.add.container(0, 0);
  const P = artPx(u);
  const h = Math.round((hCss || (isTouch() ? 44 : 40)) / PX_CSS_PER_ART) * P;
  let w = h;
  let enabled = true;
  let isPrimary = primary;
  let state = 'normal';
  const fam = () => (isPrimary ? familyOf(accent) : 'neutral');
  const panel = pixelPanel(scene, -h / 2, -h / 2, h, h, 'button-normal', { px: P });
  c.add(panel);
  const content = scene.add.container(0, 0);
  c.add(content);
  let tx = null; let ic = null; let gem = null;
  const draw = () => {
    panel.setSkin(buttonSkin(fam(), enabled ? state : 'disabled'));
    content.y = (enabled && state === 'pressed' ? P : 0) - P / 2;
    const a = enabled ? 1 : 0.45;
    tx?.setAlpha(a); ic?.setAlpha(a); gem?.setAlpha(a);
    tx?.setColor?.(enabled ? familyLabelColor(fam()) : OV.dim);
  };
  const layout = () => {
    const pad = 8 * P;
    const iconS = ic ? ic.displayWidth : 0;
    const gemS = gem ? gem.displayWidth : 0;
    const textW = tx ? tx.width : 0;
    const extra = iconS + gemS + (ic && tx ? 4 * P : 0) + (gem && tx ? 3 * P : 0);
    w = round && !tx ? h : Math.max(minW * u, textW + extra + pad * 2);
    w = Math.round(w / P) * P;
    panel.setPosition(-w / 2, -h / 2).resize(w, h);
    let cx = -(textW + extra) / 2;
    if (ic) { ic.setPosition(cx + iconS / 2, 0); cx += iconS + (tx ? 4 * P : 0); }
    if (tx) { tx.setPosition(cx, 0); cx += textW + (gem ? 3 * P : 0); }
    if (gem) gem.setPosition(cx + gemS / 2, 0);
    const hitH = Math.max(h, 48 * u);
    const hitW = Math.max(w, 48 * u);
    zone.setSize(hitW, hitH);
    if (zone.input) zone.input.hitArea.setSize(hitW, hitH);
    draw();
  };
  const zone = scene.add.zone(0, 0, h, h).setInteractive({ useHandCursor: true });
  c.add(zone);
  const setLabel = (next) => {
    const p = typeof next === 'string' ? { text: next } : (next || {});
    tx?.destroy(); ic?.destroy(); gem?.destroy();
    tx = null; ic = null; gem = null;
    if (p.text) { tx = ovText(scene, 0, 0, p.text, { u, size: 14, color: familyLabelColor(fam()) }).setOrigin(0, 0.5); content.add(tx); }
    if (p.icon) { ic = pixelIcon(scene, p.icon, (round && !p.text ? 24 : 16) * u, p.iconColor); content.add(ic); }
    if (p.gem) { gem = gemIcon(scene, 14 * u, OV.amber); content.add(gem); }
    layout();
  };
  zone.on('pointerover', () => { state = 'hover'; draw(); });
  zone.on('pointerout', () => { state = 'normal'; draw(); });
  zone.on('pointerdown', () => { state = 'pressed'; draw(); });
  zone.on('pointerup', (ptr) => { state = 'hover'; draw(); if (enabled && onClick) onClick(ptr); });
  setLabel(typeof label === 'string' ? { text: label } : (label || {}));
  return {
    container: c,
    zone,
    get w() { return w; },
    get h() { return h; },
    setLabel,
    setEnabled(v) { enabled = !!v; if (zone.input) zone.input.cursor = enabled ? 'pointer' : 'default'; draw(); return this; },
    setPrimary(v) { isPrimary = !!v; draw(); return this; }
  };
}

/** Row of level pips (filled = colour with a light top row). Returns { container, set(level, max), w }. */
export function dotsLevel(scene, level, max, { u = 1, color = OV.cyan, size = 6, gap = 4 } = {}) {
  const g = scene.add.graphics();
  const res = { container: g, w: 0 };
  const P = u; // pip bevel rows are 1 css px
  res.set = (l, m) => {
    g.clear();
    const d = Math.max(2, Math.floor(size / 2)) * 2 * u; // even css size -> whole art pixels
    const gp = Math.max(1, Math.floor(gap / 2)) * 2 * u;
    const c = colorToInt(color);
    for (let i = 0; i < m; i++) {
      const x = i * (d + gp);
      g.fillStyle(PX.ink, 1); g.fillRect(x, -d / 2, d, d);
      if (i < l) {
        g.fillStyle(c, 1); g.fillRect(x + 2 * P, -d / 2 + 2 * P, d - 4 * P, d - 4 * P);
        g.fillStyle(0xffffff, 0.55); g.fillRect(x + 2 * P, -d / 2 + 2 * P, d - 4 * P, 2 * P);
      } else {
        g.fillStyle(PX.dusk, 1); g.fillRect(x + 2 * P, -d / 2 + 2 * P, d - 4 * P, d - 4 * P);
      }
    }
    res.w = m > 0 ? m * d + (m - 1) * gp : 0;
  };
  res.set(level, max);
  return res;
}

/** Thin pixel progress bar (pct 0..1) from (0,0) to the right, vertically centred. */
export function miniBar(scene, pct, color = OV.cyan, { u = 1, w = 80, h = 6 } = {}) {
  const c = scene.add.container(0, 0);
  const H = Math.max(6, h) * u; const W = w * u; const px = u;
  c.add(pixelPanel(scene, 0, -H / 2, W, H, 'progress-track', { px }));
  const p = Phaser.Math.Clamp(Number(pct) || 0, 0, 1);
  if (p > 0) c.add(pixelPanel(scene, 0, -H / 2, Math.max(4 * px, W * p), H, progressFillSkin(familyOf(color)), { px }));
  return c;
}

/** Gap (logical units) between a key hint and the button it describes: 6 art px. */
export const hintGap = (u) => 6 * artPx(u);

/**
 * Small key hint (e.g. "Enter", "Esc") on a pixel keycap, centred on (0,0). Not a button: no hover state.
 * Width = text + 2 * 4 art px, fixed 14 art px tall, pixel font (1 font px = 1 art px) in a light tone.
 */
export function keycap(scene, label, { u = 1, size = 9, h: hCss = KEYCAP_H * PX_CSS_PER_ART, color = OV.keycapText } = {}) {
  const c = scene.add.container(0, 0);
  const P = artPx(u);
  // Pixel font on the art grid (1 font px = 1 art px) without the drop shadow, which muddies glyphs on a small cap.
  const tx = (hasUiFont(scene)
    ? pixelText(scene, 0, 0, label, { size: FONT_META.size * 2 * u, color, shadow: false })
    : ovText(scene, 0, 0, label, { u, size, color })).setOrigin(0.5);
  const hArt = Math.max(10, Math.round(hCss / PX_CSS_PER_ART));
  const m = keycapMetrics(Math.ceil(tx.width / P), { h: hArt, minW: 12 });
  const w = m.w * P; const h = m.h * P;
  c.add([pixelPanel(scene, -w / 2, -h / 2, w, h, 'keycap', { px: P }), tx]);
  // Transform#w (4D position) is reset to 0 by every setPosition(x, y): pin it to the cap width.
  Object.defineProperty(c, 'w', { get: () => w, set: () => {}, configurable: true });
  Object.defineProperty(c, 'capH', { get: () => h, set: () => {}, configurable: true });
  return c;
}

/** On/off pixel switch (centred, 44x24 css). Returns { container, set(v), get value }. */
export function toggle(scene, value, onChange, { u = 1 } = {}) {
  const c = scene.add.container(0, 0);
  const P = artPx(u);
  let v = !!value;
  const img = uiSprite(scene, 0, 0, v ? 'toggle-on' : 'toggle-off', { px: P });
  c.add(img);
  const draw = () => { if (img.setFrame) img.setFrame(v ? 'toggle-on' : 'toggle-off'); };
  const zone = scene.add.zone(0, 0, Math.max(22 * P, 48 * u), Math.max(12 * P, 48 * u)).setInteractive({ useHandCursor: true });
  zone.on('pointerup', () => { v = !v; draw(); onChange?.(v); });
  c.add(zone);
  draw();
  return { container: c, set(n) { v = !!n; draw(); }, get value() { return v; } };
}

/** Horizontal pixel slider 0..1 starting at (0,0). Returns { container, set(v), get value }. */
export function slider(scene, value, onChange, { u = 1, w = 160, accent = OV.violet } = {}) {
  const c = scene.add.container(0, 0);
  const P = artPx(u);
  const W = w * u;
  const trackH = 6 * (P / 2); // 6 art px groove at 1 css px per art px
  const track = pixelPanel(scene, 0, -trackH / 2, W, trackH, 'slider-track', { px: P / 2 });
  const fill = pixelPanel(scene, 0, -trackH / 2, W, trackH, progressFillSkin(familyOf(accent)), { px: P / 2 });
  const thumb = uiSprite(scene, 0, 0, 'slider-thumb', { px: P });
  c.add([track, fill, thumb]);
  let v = Phaser.Math.Clamp(Number(value) || 0, 0, 1);
  const draw = () => {
    const fw = Math.max(4 * (P / 2), W * v);
    fill.resize(fw, trackH);
    fill.setVisible(v > 0.001);
    thumb.setPosition(Math.round((W * v) / (P / 2)) * (P / 2), 0);
  };
  const zone = scene.add.zone(W / 2, 0, W + 24 * u, 48 * u).setInteractive({ useHandCursor: true, draggable: false });
  const fromPointer = (ptr) => {
    const m = c.getWorldTransformMatrix();
    const local = m.applyInverse(ptr.worldX, ptr.worldY);
    v = Phaser.Math.Clamp(local.x / W, 0, 1);
    draw(); onChange?.(v);
  };
  let down = false;
  zone.on('pointerdown', (p) => { down = true; fromPointer(p); });
  zone.on('pointermove', (p) => { if (down && p.isDown) fromPointer(p); });
  zone.on('pointerup', () => { down = false; });
  zone.on('pointerout', () => { down = false; });
  c.add(zone);
  draw();
  return { container: c, set(n) { v = Phaser.Math.Clamp(n, 0, 1); draw(); }, get value() { return v; } };
}

/**
 * Pixel overlay window.
 * opts: { title, icon (icon name), width/height (max css), footerH (css, 0 = none), onClose, onKey(k, event),
 *         accent, depth }
 * Returns { container, body, footer, header, u, frame, bodyRect, footerRect, close(), setScrollable(contentH),
 *           scrollTo(y), reveal(top, h), pointerInBody(ptr), dragged(), isTop() }.
 * - body: content container; local (0,0) = top-left of the scroll viewport (bodyRect.w x bodyRect.h).
 * - footer: container whose (0,0) is the footer's top-left (footerRect.w x footerRect.h).
 * - ESC closes the topmost overlay; other keys go to onKey of the topmost overlay only.
 */
export function createOverlay(scene, opts = {}) {
  const { title = '', icon = null, width = 880, height = 600, footerH = 0, onClose, onKey, accent = OV.violet, depth = OV.depth, hide = [], blockKeys = null } = opts;
  const u = overlayUnit(scene);
  const P = artPx(u);
  const view = visibleRect(scene.scale.width, scene.scale.height, scene.cameras.main.zoom);
  const frame = overlayFrame(view, u, { maxW: width, maxH: height, margin: 12 });
  // Snap the window to whole art pixels so the bevel never lands on half pixels.
  frame.w = Math.floor(frame.w / P) * P;
  frame.h = Math.floor(frame.h / P) * P;
  const cx = Math.round(frame.x + frame.w / 2);
  const cy = Math.round(frame.y + frame.h / 2);
  frame.x = cx - frame.w / 2;
  frame.y = cy - frame.h / 2;
  const stack = (scene.__titleOverlayStack ||= []);
  const motion = !reducedMotion();
  const pad = 20 * u;
  const headerH = 60 * u;
  const fH = footerH * u;

  // Objects faded out while the overlay is open (e.g. the title menu behind the window).
  const hidden = (hide || []).filter((o) => o && o.active !== false && typeof o.setAlpha === 'function').map((o) => ({ o, a: o.alpha }));
  hidden.forEach(({ o }) => { scene.tweens.killTweensOf(o); scene.tweens.add({ targets: o, alpha: 0, duration: motion ? 180 : 0 }); });
  const restoreHidden = () => hidden.forEach(({ o, a }) => {
    if (!o.scene) return;
    scene.tweens.killTweensOf(o);
    if (motion) scene.tweens.add({ targets: o, alpha: a, duration: 200 }); else o.setAlpha(a);
  });

  // Dim backdrop: flat ink + checker dither (click outside the panel closes).
  const backdrop = scene.add.rectangle(view.x + view.w / 2, view.y + view.h / 2, view.w + 8, view.h + 8, PX.ink, 0.5)
    .setDepth(depth).setAlpha(0).setInteractive();
  const dither = ditherFill(scene, view.x - 4, view.y - 4, view.w + 8, view.h + 8, { px: P, color: PX.ink, alpha: 0.55 }).setDepth(depth).setAlpha(0);

  const root = scene.add.container(cx, cy).setDepth(depth + 1);
  const L = -frame.w / 2; const T = -frame.h / 2;

  // Hard pixel drop shadow + bevelled frame.
  const shadow = scene.add.rectangle(L + 3 * P, T + 3 * P, frame.w, frame.h, PX.ink, 0.6).setOrigin(0);
  const panel = pixelPanel(scene, L, T, frame.w, frame.h, 'panel-dark', { px: P });
  const sep = scene.add.graphics();
  const engrave = (y) => {
    sep.fillStyle(PX.ink, 1); sep.fillRect(L + 4 * P, y, frame.w - 8 * P, P);
    sep.fillStyle(PX.dusk, 1); sep.fillRect(L + 4 * P, y + P, frame.w - 8 * P, P);
  };
  // Header band: slightly lighter strip under the title (flat, no gradient).
  sep.fillStyle(PX.dusk, 1); sep.fillRect(L + 4 * P, T + 4 * P, frame.w - 8 * P, headerH - 4 * P);
  engrave(T + Math.round(headerH / P) * P);
  if (fH > 0) engrave(-T - fH - P);
  const panelZone = scene.add.zone(0, 0, frame.w, frame.h).setInteractive();
  root.add([shadow, panel, sep, panelZone]);

  // Header: [icon tile] Title ............ [extras][✕]
  const header = scene.add.container(L, T);
  root.add(header);
  let tx0 = pad;
  if (icon) {
    const tileS = 18 * P;
    header.add(pixelPanel(scene, pad, Math.round((headerH - tileS) / 2 / P) * P, tileS, tileS, tileSkin(familyOf(accent)), { px: P }));
    header.add(pixelIcon(scene, icon, 16 * u).setPosition(pad + tileS / 2, Math.round((headerH - tileS) / 2 / P) * P + tileS / 2));
    tx0 = pad + tileS + 6 * P;
  }
  const titleText = ovText(scene, tx0, headerH / 2 + P, title, { u, size: 20, bold: true }).setOrigin(0, 0.5);
  header.add(titleText);

  // ✕ square pixel button.
  const closeD = 18 * P;
  const closeX = frame.w - pad - closeD / 2;
  const closeY = Math.round(headerH / 2 / P) * P + P;
  const closePanel = pixelPanel(scene, closeX - closeD / 2, closeY - closeD / 2, closeD, closeD, 'button-normal', { px: P });
  const closeIcon = pixelIcon(scene, 'close', 16 * u).setPosition(closeX, closeY - P / 2);
  const drawClose = (st) => {
    closePanel.setSkin(buttonSkin('neutral', st));
    closeIcon.y = closeY - P / 2 + (st === 'pressed' ? P : 0);
  };
  drawClose('normal');
  const closeZone = scene.add.zone(closeX, closeY, Math.max(closeD, 48 * u), Math.max(closeD, 48 * u)).setInteractive({ useHandCursor: true });
  header.add([closePanel, closeIcon, closeZone]);
  /** x (header-local) where right-side header extras should end. */
  const headerRightX = closeX - closeD / 2 - 12 * u;

  // Body viewport + mask.
  const bodyRect = { x: frame.x + pad, y: frame.y + headerH + 14 * u, w: frame.w - pad * 2, h: frame.h - overlayChromeH(footerH) * u };
  const body = scene.add.container(L + pad, T + headerH + 14 * u);
  root.add(body);
  const maskG = scene.make.graphics({ x: 0, y: 0, add: false });
  // Allow highlight overflow sideways; clip vertically.
  maskG.fillStyle(0xffffff, 1);
  maskG.fillRect(bodyRect.x - 10 * u, bodyRect.y - 6 * u, bodyRect.w + 20 * u, bodyRect.h + 12 * u);
  const mask = maskG.createGeometryMask();
  const bodyBaseY = body.y;

  const footerRect = { x: frame.x + pad, y: frame.y + frame.h - fH, w: frame.w - pad * 2, h: fH };
  const footer = scene.add.container(L + pad, -T - fH);
  root.add(footer);

  const scrollbar = scene.add.graphics().setVisible(false);
  root.add(scrollbar);

  // Scroll state.
  let contentH = 0; let scrollY = 0; let scrollable = false;
  const drawScrollbar = () => {
    scrollbar.clear();
    if (!scrollable) { scrollbar.setVisible(false); return; }
    scrollbar.setVisible(true);
    const trackH = bodyRect.h; const x = L + pad + bodyRect.w + 4 * u; const y0 = T + headerH + 14 * u;
    const thumbH = Math.max(12 * P, trackH * (bodyRect.h / contentH));
    const ty = Math.round((y0 + (trackH - thumbH) * (scrollY / Math.max(1, contentH - bodyRect.h))) / P) * P;
    scrollbar.fillStyle(PX.ink, 1); scrollbar.fillRect(x, y0, 3 * P, trackH);
    scrollbar.fillStyle(PX.periw, 1); scrollbar.fillRect(x, ty, 3 * P, thumbH);
    scrollbar.fillStyle(PX.mist, 1); scrollbar.fillRect(x, ty, 3 * P, P);
    scrollbar.fillStyle(PX.slate, 1); scrollbar.fillRect(x, ty + thumbH - P, 3 * P, P);
  };
  const applyScroll = () => { body.y = bodyBaseY - Math.round(scrollY); drawScrollbar(); };
  const scrollTo = (y, animate = false) => {
    const next = clampScroll(y, contentH, bodyRect.h);
    if (animate && motion && Math.abs(next - scrollY) > 1) {
      const o = { v: scrollY };
      scene.tweens.add({ targets: o, v: next, duration: 140, ease: 'Quad.easeOut', onUpdate: () => { scrollY = o.v; applyScroll(); } });
      scrollY = next;
      return;
    }
    scrollY = next; applyScroll();
  };
  const pointerInBody = (ptr) => {
    const px = ptr.worldX ?? ptr.x; const py = ptr.worldY ?? ptr.y;
    return px >= bodyRect.x && px <= bodyRect.x + bodyRect.w && py >= bodyRect.y && py <= bodyRect.y + bodyRect.h;
  };
  let dragStart = null; let dragMoved = false;
  const onWheel = (ptr, _objs, _dx, dy) => { if (scrollable && isTop() && pointerInBody(ptr)) scrollTo(scrollY + dy * 0.6); };
  const onDown = (ptr) => { dragMoved = false; dragStart = (scrollable && pointerInBody(ptr)) ? { y: ptr.worldY, s: scrollY } : null; };
  const onMove = (ptr) => {
    if (!dragStart || !ptr.isDown) return;
    const dy = ptr.worldY - dragStart.y;
    if (Math.abs(dy) > 8 * u) dragMoved = true;
    if (dragMoved) scrollTo(dragStart.s - dy);
  };
  const onUp = () => { dragStart = null; };
  scene.input.on('wheel', onWheel);
  scene.input.on('pointerdown', onDown);
  scene.input.on('pointermove', onMove);
  scene.input.on('pointerup', onUp);

  const api = {};
  const isTop = () => stack[stack.length - 1] === api;
  let closing = false;
  const onKeyDown = (event) => {
    if (!isTop() || closing) return;
    // A legacy modal drawn above the window (name input, rank table) owns the keyboard meanwhile.
    if (blockKeys && blockKeys()) return;
    const k = event.key?.toLowerCase?.() || event.key;
    if (k === 'escape' || k === 'esc') { close(); return; }
    onKey?.(k, event);
  };
  scene.input.keyboard?.on('keydown', onKeyDown);

  const teardown = () => {
    scene.input.keyboard?.off('keydown', onKeyDown);
    scene.input.off('wheel', onWheel);
    scene.input.off('pointerdown', onDown);
    scene.input.off('pointermove', onMove);
    scene.input.off('pointerup', onUp);
    scene.events.off('shutdown', onShutdown);
    const i = stack.indexOf(api);
    if (i >= 0) stack.splice(i, 1);
    root.destroy();
    backdrop.destroy();
    dither.destroy();
    maskG.destroy();
  };
  const onShutdown = () => { if (!closing) { closing = true; restoreHidden(); teardown(); onClose?.(); } };
  scene.events.once('shutdown', onShutdown);

  function close() {
    if (closing) return;
    closing = true;
    // Unregister the overlay immediately so the main menu (or a parent overlay) gets input back.
    const i = stack.indexOf(api);
    if (i >= 0) stack.splice(i, 1);
    restoreHidden();
    onClose?.();
    if (!motion) { teardown(); return; }
    scene.tweens.add({ targets: [backdrop, dither], alpha: 0, duration: 120 });
    scene.tweens.add({ targets: root, alpha: 0, y: cy + 4 * P, duration: 120, ease: 'Quad.easeIn', onComplete: teardown });
  }

  closeZone.on('pointerover', () => drawClose('hover'));
  closeZone.on('pointerout', () => drawClose('normal'));
  closeZone.on('pointerdown', () => drawClose('pressed'));
  closeZone.on('pointerup', () => close());
  backdrop.on('pointerup', (ptr) => {
    const px = ptr.worldX; const py = ptr.worldY;
    if (px < frame.x || px > frame.x + frame.w || py < frame.y || py > frame.y + frame.h) close();
  });

  body.setMask(mask);

  // Open: fade in while dropping 4 art px into place (positional, stays on the pixel grid).
  if (motion) {
    root.setAlpha(0).setY(cy - 4 * P);
    scene.tweens.add({ targets: root, alpha: 1, y: cy, duration: 160, ease: 'Cubic.easeOut', onUpdate: () => { root.y = Math.round(root.y); } });
    scene.tweens.add({ targets: backdrop, alpha: 1, duration: 160 });
    scene.tweens.add({ targets: dither, alpha: 0.55, duration: 160 });
  } else {
    backdrop.setAlpha(1);
    dither.setAlpha(0.55);
  }

  Object.assign(api, {
    container: root,
    backdrop,
    header,
    headerRightX,
    headerH,
    titleText,
    body,
    footer,
    u,
    px: P,
    frame,
    bodyRect,
    footerRect,
    close,
    isTop,
    isClosing: () => closing,
    pointerInBody,
    dragged: () => dragMoved,
    setScrollable(h) {
      contentH = Math.max(0, h || 0);
      scrollable = contentH > bodyRect.h + 0.5;
      scrollTo(scrollY);
      return api;
    },
    scrollTo,
    reveal(top, h) { if (scrollable) scrollTo(scrollToReveal(scrollY, bodyRect.h, top, h, 10 * u, contentH), true); },
    get scrollY() { return scrollY; }
  });
  stack.push(api);
  return api;
}

/**
 * Segmented control (e.g. EN | ES) on a pixel groove. options: [{ id, label?, icon? }]. Centred on (0,0).
 * Returns { container, w, h, set(index), get index }. Segments are >= 48 css wide/tall to hit.
 */
export function segmented(scene, options, index, onChange, { u = 1, h: hCss = 0, minSegW = 52 } = {}) {
  const c = scene.add.container(0, 0);
  const P = artPx(u);
  const h = Math.round((hCss || (isTouch() ? 40 : 34)) / PX_CSS_PER_ART) * P;
  let cur = Phaser.Math.Clamp(index | 0, 0, Math.max(0, options.length - 1));
  const segs = options.map((o) => {
    const tx = o.label ? ovText(scene, 0, 0, o.label, { u, size: 13 }).setOrigin(0.5) : null;
    const ic = o.icon ? pixelIcon(scene, o.icon, 14 * u) : null;
    const w = Math.round(Math.max(minSegW * u, (tx ? tx.width : 0) + (ic ? ic.displayWidth + 3 * P : 0) + 10 * P) / P) * P;
    return { o, tx, ic, w };
  });
  const W = segs.reduce((s, sg) => s + sg.w, 0) + 4 * P;
  const track = pixelPanel(scene, -W / 2, -h / 2, W, h, 'tab', { px: P });
  const pill = pixelPanel(scene, 0, 0, 10, 10, 'tab-active', { px: P });
  c.add([track, pill]);
  let x = -W / 2 + 2 * P;
  segs.forEach((sg) => {
    sg.x = x + sg.w / 2;
    const both = sg.tx && sg.ic;
    if (sg.ic) { sg.ic.setPosition(sg.x - (both ? sg.tx.width / 2 + 2 * P : 0), -P / 2); c.add(sg.ic); }
    if (sg.tx) { sg.tx.setPosition(sg.x + (both ? sg.ic.displayWidth / 2 + P : 0), -P / 2); c.add(sg.tx); }
    x += sg.w;
  });
  const draw = () => {
    const a = segs[cur];
    if (a) pill.setPosition(a.x - a.w / 2, -h / 2 + P).resize(a.w, h - 2 * P);
    segs.forEach((sg, i) => { sg.tx?.setColor(i === cur ? PX_CSS.white : PX_CSS.periw); sg.ic?.setAlpha(i === cur ? 1 : 0.55); });
  };
  segs.forEach((sg, i) => {
    const z = scene.add.zone(sg.x, 0, Math.max(sg.w, 48 * u), Math.max(h, 48 * u)).setInteractive({ useHandCursor: true });
    z.on('pointerup', () => { if (i === cur) return; cur = i; draw(); onChange?.(options[i].id, i); });
    c.add(z);
  });
  draw();
  return { container: c, w: W, h, set(i) { cur = Phaser.Math.Clamp(i | 0, 0, options.length - 1); draw(); }, get index() { return cur; } };
}

/** Pixel medal (ribbon + disc) centred on (0,0); tier 'gold' | 'silver' | 'bronze'. size = disc diameter (logical). */
export function medalIcon(scene, tier, size) {
  const t = ['gold', 'silver', 'bronze'].includes(tier) ? tier : 'bronze';
  const u = overlayUnit(scene);
  // The disc is ~9 of the 16 art px: pick the art scale whose disc is closest to `size`.
  const px = Math.max(1, Math.round(size / 9 / u)) * u;
  return uiIcon(scene, 0, 0, `medal-${t}`, { px });
}

/** Pixel skeleton bar (loading placeholder) from (x,y) top-left; dithered, pulses unless reduced motion. */
export function skeletonBar(scene, x, y, w, h, { u = 1 } = {}) {
  const P = artPx(u);
  const c = scene.add.container(0, 0);
  const base = scene.add.rectangle(x, y, w, h, PX.dusk, 1).setOrigin(0);
  const d = ditherFill(scene, x, y, w, h, { px: P, color: PX.slate, alpha: 0.6 });
  c.add([base, d]);
  if (!reducedMotion()) scene.tweens.add({ targets: c, alpha: { from: 1, to: 0.45 }, duration: 700, yoyo: true, repeat: -1, ease: 'Stepped', easeParams: [4] });
  return c;
}

/** Opaque mix of colour a over b (k = weight of a). */
export function mixColor(a, b, k) {
  const A = colorToInt(a); const B = colorToInt(b);
  const ch = (s) => Math.round(((A >> s) & 255) * k + ((B >> s) & 255) * (1 - k)) << s;
  return ch(16) | ch(8) | ch(0);
}

/**
 * Chunky pixel disc / ellipse centred on (x, y) drawn on the art grid (rx, ry in logical units; ry defaults to rx).
 * fill: colour; line: outline colour (1 art px); light: optional top crescent (1 art px) colour.
 * Pass { g } to draw into an existing Graphics (not cleared). Returns the Graphics.
 */
export function pixelDisc(scene, x, y, rx, { u = 1, ry = rx, fill = PX.night, line = null, light = null, alpha = 1, g = null, px = null } = {}) {
  const gr = g || scene.add.graphics();
  const P = px || artPx(u);
  const RX = Math.max(1, Math.round(rx / P)); const RY = Math.max(1, Math.round(ry / P));
  const half = (a, b, j) => (j < -b || j >= b ? 0 : Math.round(a * Math.sqrt(Math.max(0, 1 - ((j + 0.5) / b) ** 2))));
  const row = (j, h, col) => { if (h > 0) { gr.fillStyle(col, alpha); gr.fillRect(x - h * P, y + j * P, h * 2 * P, P); } };
  if (line != null) for (let j = -RY; j < RY; j++) row(j, half(RX, RY, j), colorToInt(line));
  const ix = line != null ? RX - 1 : RX; const iy = line != null ? RY - 1 : RY;
  const lit = light != null && ix > 1 && iy > 1;
  for (let j = -iy; j < iy; j++) {
    const h = half(ix, iy, j);
    if (lit) { row(j, h, colorToInt(light)); row(j, Math.min(h, half(ix, iy, j - 1)), colorToInt(fill)); } else row(j, h, colorToInt(fill));
  }
  return gr;
}

/** Small round "i" badge centred on (0,0) (rules / hints). size = diameter in logical units. */
export function infoBadge(scene, size, { u = 1, color = PX.slate } = {}) {
  const c = scene.add.container(0, 0);
  const P = artPx(u);
  const r = Math.max(4 * P, Math.round(size / 2 / P) * P);
  c.add(pixelDisc(scene, 0, 0, r, { u, fill: colorToInt(color), line: PX.ink, light: PX.periw }));
  // Hand-placed glyph (2 art px wide): dot, gap, 4 px stem, on the disc's pixel grid.
  const g = scene.add.graphics();
  g.fillStyle(PX.white, 1);
  g.fillRect(-P, -4 * P, 2 * P, 2 * P);
  g.fillRect(-P, -P, 2 * P, 4 * P);
  c.add(g);
  Object.defineProperty(c, 'w', { get: () => r * 2, set: () => {}, configurable: true });
  return c;
}

/**
 * Status chip: bevelled 'chip' 9-slice with a leading icon (display object) and a label, left edge at (0,0),
 * vertically centred. Returns { container, w, h, setLabel(str, color), setIcon(obj) }.
 */
export function iconChip(scene, icon, label, { u = 1, size = 13, color = OV.text, h: hCss = 28, skin = 'chip' } = {}) {
  const c = scene.add.container(0, 0);
  const P = artPx(u);
  const h = Math.round(hCss / PX_CSS_PER_ART) * P;
  const panel = pixelPanel(scene, 0, -h / 2, h, h, skin, { px: P });
  c.add(panel);
  let ic = icon || null;
  const tx = ovText(scene, 0, -P / 2, label, { u, size, color }).setOrigin(0, 0.5);
  c.add(tx);
  if (ic) c.add(ic);
  const res = { container: c, w: h, h };
  const layout = () => {
    const pad = 5 * P;
    let x = pad;
    if (ic) { const iw = ic.displayWidth || ic.w || 0; ic.setPosition(x + iw / 2, 0); x += iw + 3 * P; }
    tx.setX(x);
    x += tx.width + pad;
    res.w = Math.round(x / P) * P;
    panel.resize(res.w, h);
  };
  res.setLabel = (s, col) => { tx.setText(s); if (col != null) tx.setColor?.(col); layout(); return res; };
  res.setIcon = (obj) => { ic?.destroy(); ic = obj || null; if (ic) c.add(ic); layout(); return res; };
  layout();
  return res;
}
