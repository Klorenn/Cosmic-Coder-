/**
 * Pixel overlay kit for the title submenus (UPGRADES / WEAPONS / CHARACTER / LEADERBOARD / SETTINGS /
 * CONTROLS / CREDITS) — ui/pixel-kit-v3. Same API as the old glass kit, new render:
 * bevelled 9-slice panels, bitmap pixel font, chunky outlined icons, hard 1 px shadows, dithered dims.
 *
 * Every size argument is in CSS px; the kit converts to logical canvas units with overlayUnit(scene)
 * (the canvas is 1920x1080 FIT-scaled, and TitleScene zooms the camera on short windows).
 * One art pixel = PX_CSS_PER_ART (2) css px everywhere, so bevels, icons and glyphs share a pixel grid.
 * Art comes from boot/uiAssets.js (generated by scripts/assets/gen-ui.mjs). Pure maths: overlayModel.js.
 */
